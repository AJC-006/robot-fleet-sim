#!/usr/bin/env python3
"""Write src/fleet_drone/models/wyvern/model.sdf from PX4's x500_base + x500 models.

Links, joints and collisions are copied unchanged from PX4-Autopilot/Tools/simulation/gz/models (BSD 3-Clause,
Rudis Laboratories / PX4). Sensors (ICM-42688-P, MS5611, IST8310, MAX-M10S + GnssError plugin) and the motor
constants (T-Motor AIR2216II KV920 + T1045 thrust table) come from the component catalog. The visuals are replaced by the Blender-built wyvern meshes, and a PosePublisher is added so tests can
compare PX4's estimate against ground truth.

    python3 blender/drone/make_sdf.py [--px4 ~/PX4-Autopilot]
"""
import argparse
import copy
import os
import xml.etree.ElementTree as ET

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "fleet_drone", "models", "wyvern", "model.sdf")
CAT = os.path.join(ROOT, "src", "fleet_components", "components")

HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
  wyvern: PX4 SITL quadcopter for robot-fleet-sim.
  Generated by blender/drone/make_sdf.py from PX4-Autopilot Tools/simulation/gz/models/x500_base and x500
  (BSD 3-Clause, Copyright (c) 2022 Rudis Laboratories, author Benjamin Perseghetti; see LICENSE).
  Links, collisions and joints are unchanged from x500 (PX4 airframe 4001_gz_x500). The sensors and the
  motor/propeller constants are NOT x500 values: they are generated from the component catalog
  (src/fleet_components/components, see docs/notes/air.md). Base-link mass and inertia, rotor drag and
  rolling-moment coefficients remain the x500 values (unsourced, listed in the audit in docs/notes/air.md).
  Visuals: self-made Blender meshes (blender/drone/build_drone.py).
-->
"""


def sub(parent, tag, text=None, **attrib):
    e = ET.SubElement(parent, tag, attrib)
    if text is not None:
        e.text = text
    return e


def mesh_visual(link, name, uri, pose="0 0 0 0 0 0", cast_shadows=True):
    v = sub(link, "visual", name=name)
    sub(v, "pose", pose)
    g = sub(sub(v, "geometry"), "mesh")
    sub(g, "uri", uri)
    sub(v, "cast_shadows", "true" if cast_shadows else "false")
    return v


def cat(path):
    with open(os.path.join(CAT, path)) as fh:
        return yaml.safe_load(fh)


def noise(parent, tag, stddev, bias_stddev=0.0, dyn_stddev=None, tau=None, precision=None):
    n = sub(sub(parent, tag), "noise", type="gaussian_quantized" if precision else "gaussian")
    sub(n, "mean", "0")
    sub(n, "stddev", repr(float(stddev)))
    sub(n, "bias_mean", "0")
    sub(n, "bias_stddev", repr(float(bias_stddev)))
    if dyn_stddev is not None:
        sub(n, "dynamic_bias_stddev", repr(float(dyn_stddev)))
        sub(n, "dynamic_bias_correlation_time", repr(float(tau)))
    if precision:
        sub(n, "precision", repr(float(precision)))


def sensor(link, name, typ, rate):
    s = sub(link, "sensor", name=name, type=typ)
    sub(s, "gz_frame_id", "base_link")
    sub(s, "always_on", "1")
    sub(s, "update_rate", str(rate))
    return s


def catalog_sensors(base_link):
    """Replace the x500 sensor set with catalog-derived sensors; return the GnssError plugin config."""
    for old in base_link.findall("sensor"):
        base_link.remove(old)
    imu_c, baro_c = cat("fc_imu/tdk_icm_42688_p.yaml")["sim"], cat("barometer/te_ms5611_01ba03.yaml")["sim"]
    mag_c, gnss_c = cat("magnetometer/isentek_ist8310.yaml")["sim"], cat("gnss/ublox_max_m10s.yaml")["sim"]
    s = sensor(base_link, "air_pressure_sensor", "air_pressure", baro_c["update_rate"])
    noise(sub(s, "air_pressure"), "pressure", baro_c["stddev"], baro_c["bias_stddev"], precision=baro_c["precision"])
    s = sensor(base_link, "magnetometer_sensor", "magnetometer", mag_c["update_rate"])
    m = sub(s, "magnetometer")
    for ax in "xyz":
        noise(m, ax, mag_c["stddev"], mag_c["bias_stddev"], precision=mag_c["precision"])
    s = sensor(base_link, "imu_sensor", "imu", imu_c["update_rate"])
    i = sub(s, "imu")
    tau = imu_c["bias_correlation_time"]
    av = sub(i, "angular_velocity")
    for ax in "xyz":
        noise(av, ax, imu_c["gyro_noise_stddev"], imu_c["gyro_bias_stddev"], imu_c["gyro_dynamic_bias_stddev"], tau)
    la = sub(i, "linear_acceleration")
    for ax in "xyz":
        z = ax == "z"
        noise(la, ax, imu_c["accel_noise_stddev_z" if z else "accel_noise_stddev_xy"], imu_c["accel_bias_stddev"],
              imu_c["accel_dynamic_bias_stddev_z" if z else "accel_dynamic_bias_stddev_xy"], tau)
    sensor(base_link, "navsat_truth", "navsat", 10)  # error-free; GnssError republishes it as navsat_sensor
    return gnss_c


def gnss_plugin(model, g):
    p = sub(model, "plugin", filename="fleet_gnss_error", name="fleet_aircraft::GnssError")
    sub(p, "link", "base_link")
    sub(p, "input_sensor", "navsat_truth")
    sub(p, "output_sensor", "navsat_sensor")
    sub(p, "horizontal_stddev_m", repr(float(g["horizontal_stddev_m"])))
    sub(p, "vertical_stddev_m", repr(float(g["vertical_stddev_m"])))
    sub(p, "position_correlation_time_s", repr(float(g["position_correlation_time_s"])))
    sub(p, "velocity_stddev_mps", repr(float(g["velocity_stddev_mps"])))
    sub(p, "seed", "0")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--px4", default=os.environ.get("PX4_DIR", os.path.expanduser("~/PX4-Autopilot")))
    a = ap.parse_args()
    mdir = os.path.join(a.px4, "Tools", "simulation", "gz", "models")
    base = ET.parse(os.path.join(mdir, "x500_base", "model.sdf")).getroot().find("model")
    top = ET.parse(os.path.join(mdir, "x500", "model.sdf")).getroot().find("model")

    sdf = ET.Element("sdf", version="1.9")
    model = sub(sdf, "model", name="wyvern")
    for child in base:
        c = copy.deepcopy(child)
        if c.tag == "link":
            # insert the new visuals where the old ones were (before collisions) to keep the file readable
            olds = [v for v in c.findall("visual")]
            idx = list(c).index(olds[0]) if olds else len(c)
            for v in olds:
                c.remove(v)
            name = c.get("name")
            if name == "base_link":
                vis = [("wyvern_body_visual", "model://wyvern/meshes/wyvern_body.glb", "0 0 0 0 0 0")]
            else:
                turn = None
                for p in top.findall("plugin"):
                    if p.findtext("linkName") == name:
                        turn = p.findtext("turningDirection")
                vis = [(name + "_visual", "model://wyvern/meshes/wyvern_rotor_%s.glb" % turn, "0 0 0 0 0 0")]
            tmp = ET.Element("tmp")
            for (n, uri, pose) in vis:
                mesh_visual(tmp, n, uri, pose)
            for k, v in enumerate(list(tmp)):
                c.insert(idx + k, v)
        if c.tag == "link" and c.get("name") == "base_link":
            gnss_cfg = catalog_sensors(c)
        if c.tag == "link" and c.get("name", "").startswith("rotor_"):
            # T1045 propeller: 13 g, inertia about the spin axis from the catalog (rod upper bound)
            prop = cat("propeller/tmotor_t1045.yaml")["specs"]
            J = prop["inertia_about_axis"]
            inr = c.find("inertial")
            m0 = float(inr.find("mass").text)
            inr.find("mass").text = repr(float(prop["mass"]))
            iner = inr.find("inertia")
            iner.find("izz").text = repr(float(J))
            iner.find("iyy").text = repr(float(J))
            # ixx (about the blade span axis) is only scaled with mass from the x500 value; it is ~100x smaller than
            # iyy/izz and does not enter the motor model
            iner.find("ixx").text = repr(float(float(iner.find("ixx").text) * prop["mass"] / m0))
        model.append(c)
    mot = cat("propeller/tmotor_t1045.yaml")["sim"]
    mot2 = cat("bldc_motor/tmotor_air2216ii_kv920.yaml")["sim"]
    for p in top.findall("plugin"):
        if p.get("filename") == "MotorFailurePlugin":
            continue  # optional PX4 plugin (needs PX4's gz_plugins dir on GZ_SIM_SYSTEM_PLUGIN_PATH)
        p = copy.deepcopy(p)
        for tag, val in (("motorConstant", mot["motor_constant"]), ("momentConstant", mot["moment_constant"]),
                         ("maxRotVelocity", mot["max_rot_velocity"]),
                         ("timeConstantUp", mot2["time_constant_up"]), ("timeConstantDown", mot2["time_constant_down"])):
            p.find(tag).text = repr(float(val))
        model.append(p)
    gnss_plugin(model, gnss_cfg)
    pp = sub(model, "plugin", filename="gz-sim-pose-publisher-system", name="gz::sim::systems::PosePublisher")
    sub(pp, "publish_link_pose", "false")
    sub(pp, "publish_visual_pose", "false")
    sub(pp, "publish_collision_pose", "false")
    sub(pp, "publish_sensor_pose", "false")
    sub(pp, "publish_model_pose", "true")
    sub(pp, "publish_nested_model_pose", "false")
    sub(pp, "use_pose_vector_msg", "false")
    sub(pp, "static_publisher", "false")
    sub(pp, "update_frequency", "50")
    ET.indent(sdf, "  ")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(HEADER + ET.tostring(sdf, encoding="unicode") + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
